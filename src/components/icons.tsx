export function PetalDividerGlyph({
  variant,
  className,
  ...props
}: SVGProps<SVGSVGElement> & { variant: PetalDividerVariant }) {
  const { viewBox, paths } = PETAL_DIVIDERS[variant];
  return (
    <svg
      viewBox={viewBox}
      preserveAspectRatio="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      className={cn("absolute inset-0 h-full w-full text-ink", className)}
      {...props}
    >
      {paths.map((d) => (
        <path key={d} d={d} fill="currentColor" fillOpacity={0.5} />
      ))}
    </svg>
  );
}
